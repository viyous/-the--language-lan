@dataclass(frozen=True)
class Record:
    identity: str
    fields: tuple[tuple[str, Scalar | Array | Record], ...]
    repr_c: bool = False
    key_type: Scalar | None = None

    @cached_property
    def c(self):
        # Include the complete contract to keep separately emitted interfaces
        # from silently sharing a C tag with a different physical layout.
        return "lan_record_" + digest(json.dumps(encode_interface_type(self), sort_keys=True))[:24]

    @cached_property
    def alignment(self):
        return max(storage_alignment(ty) for _, ty in self.fields)

    @cached_property
    def leaves(self):
        return sum(ty.leaves if isinstance(ty, Record) else 1
                   for ty in (unqualified(field) for _, field in self.fields))

    @cached_property
    def max_bytes(self):
        def align(offset, alignment):
            return (offset + alignment - 1) // alignment * alignment

        total = 0
        for _, ty in self.layout:
            ty = unqualified(ty)
            a = storage_alignment(ty)
            total = align(total, a)
            total += storage_size(ty)
        return align(total, self.alignment)

    @property
    def layout(self):
        if self.repr_c:
            return self.fields
        return tuple(sorted(self.fields, key=lambda field: -storage_alignment(field[1])))

    @staticmethod
    def valid_keys(key_type, fields):
        if not isinstance(key_type, Scalar) or key_type.enum is None:
            return False
        members = key_type.enum.members
        size = len(members)
        return (size == len(fields) and key_type.domain == Domain.of((0, size - 1))
                and set(value for _, value in members) == set(range(size))
                and {name for name, _ in fields} == {name for name, _ in members})

    @cached_property
    def keyed_fields(self):
        fields = dict(self.fields)
        return tuple((name, fields[name]) for name, _ in sorted(
            self.key_type.enum.members, key=lambda item: item[1]))


def storage_alignment(ty):
    ty = unqualified(ty)
    if isinstance(ty, (Slice, RecordLink, Interface, ExternCallable)):
        return 8
    if isinstance(ty, Record):
        return ty.alignment
    return (storage_alignment(ty.element) if isinstance(ty, Array) and not ty.packed_bits
            else 1 if isinstance(ty, Array) else ty.bits // 8)


def storage_size(ty):
    ty = unqualified(ty)
    if isinstance(ty, (RecordLink, ExternCallable)):
        return 8
    if isinstance(ty, (Slice, Interface)):
        return 16
    if isinstance(ty, Record):
        return ty.max_bytes
    if isinstance(ty, Array):
        return ty.c_length * (1 if ty.packed_bits else storage_size(ty.element))
    return ty.bits // 8


