def is_callback_enum(enum):
    return enum is not None and enum.name == "<callback>"


def contains_callable(ty, records=None, seen=frozenset()):
    def contains(child):
        return contains_callable(child, records, seen)

    if isinstance(ty, Scalar):
        return is_callback_enum(ty.enum)
    if isinstance(ty, ExternCallable):
        return contains(ty.contract)
    if isinstance(ty, TaggedResult):
        return contains(ty.success)
    if isinstance(ty, RecordLink) and records is not None and ty.identity not in seen:
        return contains_callable(records.get(ty.identity), records, seen | {ty.identity})
    if isinstance(ty, Contract):
        return any(map(contains, ty.params)) or contains(ty.result)
    if isinstance(ty, TypeObject):
        return any(value.kind == "resolved_type" and contains(value.args[0]) for _, value in ty.entries)
    if isinstance(ty, (ReadOnly, HeapObject, StaticReadOnly)):
        return contains(ty.base)
    if isinstance(ty, BorrowScalar):
        return contains(ty.scalar)
    if isinstance(ty, (BorrowArray, CopyArray)):
        return contains(ty.array)
    if isinstance(ty, (BorrowRecord, CopyRecord, HeapRecord)):
        return contains(ty.record)
    if isinstance(ty, (Slice, Array, HeapArray)):
        return contains(ty.element)
    if isinstance(ty, (Record, Interface)):
        return any(contains(field) for _, field in ty.fields)
    if isinstance(ty, AliasResult):
        return contains(ty.alias) or any(map(contains, ty.graph_records))
    if isinstance(ty, InterfaceResult):
        return contains(ty.interface)
    return False


