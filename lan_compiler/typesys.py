@dataclass(frozen=True)
class Scalar:
    domain: Domain
    bits: int = 0
    signed: bool = False
    boolean: bool = False
    computed: bool = False
    enum: EnumInfo | None = None
    result_arms: tuple[Domain, Domain] | tuple[FloatDomain, FloatDomain] | None = field(default=None, compare=False, repr=False)
    character: str | None = None
    floating: bool = False
    result_error_enums: tuple[str, ...] = field(default=(), compare=False, repr=False)
    float_literals: tuple[Fraction | str, ...] = field(default=(), compare=False, repr=False)

    def narrow_domain(self, domain):
        arms = tuple(arm & domain for arm in self.result_arms) if self.result_arms is not None else None
        if arms is not None and any(arms):
            return replace(self, domain=domain, result_arms=arms, float_literals=(),
                           result_error_enums=self.result_error_enums if arms[1] else ())
        return replace(self, domain=domain, result_arms=None, result_error_enums=(), float_literals=())

    @property
    def c(self):
        if self.floating:
            return "float" if self.bits == 32 else "double"
        return "uint8_t" if self.boolean else f"{'' if self.signed else 'u'}int{self.bits}_t"


