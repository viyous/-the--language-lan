def bit_literal_value(node):
    """Fold expressions on fixed-width bit literals before scalar lowering."""
    if node.kind == "bit_literal":
        return node.args
    if node.kind == "unary" and node.args[0] == "~":
        operand = bit_literal_value(node.args[1])
        if operand is not None:
            value, width = operand
            return value ^ ((1 << width) - 1), width
    if node.kind == "binary":
        op, lhs, rhs = node.args
        if op not in ("&", "|", "^", "<<", ">>"):
            return None
        left = bit_literal_value(lhs)
        if left is None:
            return None
        value, width = left
        if op in ("<<", ">>") and rhs.kind in ("number", "bit_literal"):
            return bit_literal_shift(op, value, width, rhs.args[0]), width
        right = bit_literal_value(rhs)
        if right is None or op in ("<<", ">>"):
            return None
        if width != right[1]:
            node.token.error("bit literal operands require equal widths")
        return {"&": int.__and__, "|": int.__or__, "^": int.__xor__}[op](value, right[0]), width
    return None


def bit_literal_bytes(value, width):
    return "{" + ", ".join(f"0x{byte:02x}" for byte in value.to_bytes((width + 7) // 8, "little")) + "}"


def bit_literal_shift(op, value, width, count):
    if count >= width:
        return 0
    return (value << count) & ((1 << width) - 1) if op == "<<" else value >> count


def bit_literal_width(node):
    literal = bit_literal_value(node)
    if literal is not None:
        return literal[1]
    if node.kind == "binary" and node.args[0] in ("<<", ">>"):
        operand = bit_literal_value(node.args[1])
        if operand is not None:
            return operand[1]
    return None


def require_bit_literal_width(token, expected, actual):
    if actual != expected:
        token.error(f"bit literal width {actual} does not match destination width {expected}")


def require_bit_slice_literal_width(token, domain, width):
    if domain != Domain.point(width):
        token.error(f"cannot prove bit slice width equals the {width}-bit literal width")


