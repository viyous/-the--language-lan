@dataclass(frozen=True)
class AffineForm:
    origin: ValueOrigin
    scale: int = 1
    offset: int = 0

    def transform(self, scale, offset):
        return AffineForm(self.origin, self.scale * scale, self.offset * scale + offset)

    def preimage(self, domain):
        """Conservative constraints on the original value."""
        if self.scale in (1, -1):
            return domain.affine(self.scale, -self.offset * self.scale)
        if not self.scale:
            return self.origin.domain
        scale = abs(self.scale)
        spans = []
        for lo, hi in domain.ranges:
            low, high = lo - self.offset, hi - self.offset
            if self.scale < 0:
                low, high = -high, -low
            spans.append((-((-low) // scale), high // scale))
        return Domain.of(*spans)


@dataclass(frozen=True)
class Value:
    domain: Domain
    code: str
    width: int = 0
    boolean: bool = False
    affine: AffineForm | None = None
    difference: Difference | None = None
    enum: EnumInfo | None = None
    character: str | None = None
    effectful: bool = False
    versions: tuple = ()
    signed: bool = False
    literal: str | None = None
    result_arms: tuple[Domain, Domain] | tuple[FloatDomain, FloatDomain] | None = None
    linear: tuple | None = None
    result_error_enums: tuple[str, ...] = ()
    guarded_enums: frozenset[str] = frozenset()
    always_returns: bool = False

    @property
    def floating(self):
        return isinstance(self.domain, FloatDomain)

    @property
    def intermediate_c(self):
        if self.floating:
            return "float" if self.domain.bits == 32 else "double"
        if not self.boolean and bool(self.domain):
            if 0 <= self.domain.lo and self.domain.hi <= (1 << 32) - 1:
                return "uint32_t"
            if -(1 << 31) <= self.domain.lo and self.domain.hi <= (1 << 31) - 1:
                return "int32_t"
            if self.domain.lo >= 0 and self.domain.hi >= (1 << 63):
                return "lan_uint"
        return "lan_int"


@dataclass(frozen=True)
class Span:
    element: Scalar
    length: Value
    depth: int
    code: str = ""
    host: Symbol | None = None
    offset: int = 0
    borrowed_from: frozenset[Symbol] = frozenset()
    readonly: bool = False
    text: str | TextEncoding | None = None
    terminated: bool = False
    origins: tuple = ()
    start: Value | None = None
    relative_bounds: tuple[Value, Value, bool] | None = field(default=None, compare=False, hash=False)
    known_text: bytes | None = None
    bounds_proven: bool = field(default=False, compare=False, hash=False)
    row_identity: tuple | None = field(default=None, compare=False, hash=False)

    def positions(self):
        if self.origins:
            return self.origins
        if self.host is not None:
            return ((self.host, Domain.point(self.offset)),)
        return tuple((owner, None) for owner in self.owners)

    @property
    def owners(self):
        return self.borrowed_from or (frozenset((self.host,)) if self.host is not None else frozenset())

    def c_data(self):
        if self.host is not None:
            return f"({self.host.c} + {self.offset})" if self.offset else self.host.c
        qualifier = "const " if self.readonly else ""
        return f"(({qualifier}{self.element.c} *)({self.code}).data)"

    def c_value(self):
        if self.host is not None:
            return f"((lan_slice){{{self.c_data()}, {self.length.domain.lo}}})"
        return self.code


